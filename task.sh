#!/bin/bash

# ==============================================================================
# Скрипт автоматического резервного копирования и восстановления баз данных
# ==============================================================================

# Проверка наличия обязательных переменных окружения
if [ -z "$DB_USER" ] || [ -z "$DB_PASSWORD" ]; then
    echo "Ошибка: Переменные окружения DB_USER и DB_PASSWORD должны быть установлены!" >&2
    exit 1
fi

echo "=== Запуск процедуры ночного бэкапа и синхронизации ==="

# ------------------------------------------------------------------------------
# Этап 1: Полный бэкап ShopDB и полное восстановление в ShopDBReserve
# ------------------------------------------------------------------------------
echo "1. Создание полного бэкапа ShopDB..."
# --single-transaction используется для InnoDB таблиц, чтобы избежать их блокировки
mysqldump -u "$DB_USER" -p"$DB_PASSWORD" --single-transaction ShopDB > full_backup.sql

echo "2. Восстановление всей структуры и данных в ShopDBReserve..."
mysql -u "$DB_USER" -p"$DB_PASSWORD" ShopDBReserve < full_backup.sql


# ------------------------------------------------------------------------------
# Этап 2: Бэкап ТОЛЬКО ДАННЫХ из ShopDB и перенос в ShopDBDevelopment
# ------------------------------------------------------------------------------
echo "3. Экспорт данных из ShopDB (без структуры таблиц)..."
# --no-create-info (-t) исключает инструкции CREATE TABLE из дампа
# --insert-ignore предотвращает ошибки дублирования ключей, если в dev-базе уже есть данные
mysqldump -u "$DB_USER" -p"$DB_PASSWORD" --single-transaction --no-create-info --insert-ignore ShopDB > data_only_backup.sql

echo "4. Загрузка данных в ShopDBDevelopment..."
mysql -u "$DB_USER" -p"$DB_PASSWORD" ShopDBDevelopment < data_only_backup.sql


# ------------------------------------------------------------------------------
# Этап 3: Очистка временных файлов
# ------------------------------------------------------------------------------
echo "5. Удаление временных sql-файлов..."
rm full_backup.sql data_only_backup.sql

echo "=== Процедура ночного бэкапа и синхронизации успешно завершена! ==="
